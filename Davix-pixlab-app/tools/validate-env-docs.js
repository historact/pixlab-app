const allKnown = new Set([...runtime, ...scriptOnly]);
const files = ['docs/02-env-catalog.md', 'docs/16-env-reference.md', 'docs/17-env-usage-inventory.md'];
function fail(msg){ console.error(`FAIL: ${msg}`); process.exitCode = 1; }
function getBacktickedEnvTokens(content){
  const out = new Set(); let m; const re = /`([A-Z][A-Z0-9_]+)`/g;
  while ((m = re.exec(content))) out.add(m[1]);
  return out;
}
function getScriptSection(content){
  const m = content.match(/^##\s+SCRIPT-ONLY\s*\/\s*TOOLING.*$/im);
  if (!m || m.index == null) return '';
  return content.slice(m.index);
}
for (const file of files){
  const content = fs.readFileSync(path.join(process.cwd(), file), 'utf8');
  const tokens = getBacktickedEnvTokens(content);
  for (const key of runtime) if (!tokens.has(key)) fail(`${file} missing runtime key ${key}`);
  for (const key of scriptOnly) if (!tokens.has(key)) fail(`${file} missing script-only key ${key}`);
  const scriptSection = getScriptSection(content);
  if (!scriptSection) fail(`${file} missing SCRIPT-ONLY / TOOLING section`);
  const scriptTokens = getBacktickedEnvTokens(scriptSection);
  for (const key of scriptOnly) if (!scriptTokens.has(key)) fail(`${file} script-only section missing ${key}`);
  for (const t of tokens){
    if (!allKnown.has(t)) fail(`${file} has unknown env key ${t}`);
    if (/_MS$/.test(t)) fail(`${file} contains deprecated *_MS key ${t}`);
  }
  if (!/Total referenced in repo:\s*\*\*196\*\*/.test(content)) fail(`${file} missing total 196`);
  if (!/Runtime env vars:\s*\*\*187\*\*/.test(content)) fail(`${file} missing runtime total 187`);
  if (!/Script-only env vars:\s*\*\*9\*\*/.test(content)) fail(`${file} missing script-only total 9`);
}
if (process.exitCode) process.exit(process.exitCode);
console.log('PASS: env docs validation succeeded');
